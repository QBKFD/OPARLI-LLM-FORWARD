#!/usr/bin/env python3
"""Tables for REPORT.md from results/results_sigma.json and results/coefs.csv.

    .venv/bin/python research/sigma_compare/tables_sigma.py   # -> results/summary_sigma.md
"""

import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
NAMES = {"a": "plug-in", "b": "HAR", "c": "EWMA"}
KS = ("0.5", "1.0", "1.5", "2.0")


def main_table(e, verdict=None, H=None):
    out = ["| candidate | n | QLIKE | log-MSE | RV/h mean | median | p10 | p90 | ΣRV/Σh | DM vs plug-in (p) |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    a = e["all"]
    for c in "abc":
        d = a[c]
        if c == "a":
            dm = "-"
        else:
            t = e["dm"][f"{c}|a"]
            dm = f"{t['stat']:+.2f} ({t['p']:.2g})"
            if verdict is not None:
                v = verdict["tests"][f"{c}|H{H}"]
                dm += f", BH p {v['p_adj']:.2g}, **{'significant' if v['significant'] else 'not significant'}**"
        out.append(f"| {NAMES[c]} | {a['n']:,} | {d['qlike']:.4f} | {d['logmse']:.4f} | {d['cal_mean']:.3f} | "
                   f"{d['cal_median']:.3f} | {d['cal_p10']:.3f} | {d['cal_p90']:.3f} | {d['cal_pooled']:.3f} | {dm} |")
    return out


def touch_table(e, normal):
    out = ["| candidate | " + " | ".join(f"k={k} up / down" for k in KS) + " |",
           "|---|" + "---|" * len(KS)]
    for c in "abc":
        d = e["all"][c]
        out.append(f"| {NAMES[c]} | " + " | ".join(f"{d[f'up_{k}']:.3f} / {d[f'dn_{k}']:.3f}" for k in KS) + " |")
    out.append("| normal theory | " + " | ".join(f"{normal[k]:.3f}" for k in KS) + " |")
    return out


def main():
    R = json.load(open(RES / "results_sigma.json"))
    v, normal = R["verdict"], R["normal_touch"]
    L = ["# sigma_compare: tables", "",
         f"Generated by tables_sigma.py. **Verdict: {v['choice_name']}** ({v['why']}).", ""]
    for p in ("CONF", "DEV"):
        rows = R[p]["rows"]
        L += [f"## {p}", "",
              "Rows (common to all candidates): " + "; ".join(
                  f"H={h[1:]}: {r['common']:,} of {r['all']:,} test labels "
                  f"({r['noncross']:,} non-crossing, {r['cross']:,} crossing)" for h, r in rows.items()),
              f"Plug-in identity checks passed: {R[p]['n_plugin_checked']:,}.", ""]
        for kind, title in (("noncross", "non-crossing windows"), ("cross", "windows crossing a close")):
            for H in (60, 240):
                e = R[p]["eval"].get(f"H{H}_{kind}")
                if e is None:
                    continue
                tag = " (VERDICT SAMPLE)" if p == "CONF" and kind == "noncross" else ""
                L += [f"### {p}, H = {H}, {title}{tag}", ""]
                L += main_table(e, v if tag else None, H) + [""]
                L += ["Touch rates (σ_px = close_ref·√h):", ""] + touch_table(e, normal) + [""]
                bc, lm = e["dm"]["b|c"], e["dm_logmse"]
                L += [f"DM HAR vs EWMA (QLIKE): {bc['stat']:+.2f} (p {bc['p']:.2g}). "
                      f"DM on log-MSE vs plug-in: HAR {lm['b|a']['stat']:+.2f} (p {lm['b|a']['p']:.2g}), "
                      f"EWMA {lm['c|a']['stat']:+.2f} (p {lm['c|a']['p']:.2g}).", ""]
                if "eras" in e:
                    L += ["| era | n | QLIKE plug-in | HAR | EWMA | DM HAR vs plug-in | DM EWMA vs plug-in |",
                          "|---|---:|---:|---:|---:|---:|---:|"]
                    for era, ee in e["eras"].items():
                        mq = ee["metrics"]
                        L.append(f"| {era} | {mq['n']:,} | {mq['a']['qlike']:.4f} | {mq['b']['qlike']:.4f} | "
                                 f"{mq['c']['qlike']:.4f} | {ee['dm']['b|a']['stat']:+.2f} | "
                                 f"{ee['dm']['c|a']['stat']:+.2f} |")
                    L.append("")
                f = pd.DataFrame(e["folds"])
                L += [f"Folds where QLIKE is lower than the plug-in's: HAR {int((f.b < f.a).sum())}/{len(f)}, "
                      f"EWMA {int((f.c < f.a).sum())}/{len(f)}; HAR below EWMA {int((f.b < f.c).sum())}/{len(f)}.", ""]
    c = pd.read_csv(RES / "coefs.csv")
    g = c.groupby(["period", "H"])
    L += ["## Fitted per fold (exploratory)", "",
          "| period | H | b0 | bL | bS_hd | bT | smearing c | EWMA half-lives (returns) |",
          "|---|---:|---|---|---|---|---|---|"]
    for (p, H), x in g:
        rng = lambda s: f"{x[s].min():.3f} .. {x[s].max():.3f}"   # noqa: E731
        L.append(f"| {p} | {H} | {rng('b0')} | {rng('bL')} | {rng('bS_hd')} | {rng('bT')} | {rng('smear_c')} | "
                 f"{', '.join(map(str, sorted(set(x.half_life))))} |")
    (RES / "summary_sigma.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
