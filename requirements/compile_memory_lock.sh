#!/usr/bin/env bash
# Recompile requirements/requirements-memory.lock (tools/research_memory).
# Constrained to every pin of requirements/requirements.lock and
# requirements/requirements-studio.lock (shared packages stay identical) except setuptools:
# torch 2.11.0 (the last release with macOS 11+ arm64 wheels) needs
# setuptools<82, and the main lock pins 84.0.0 as a build tool. The memory venv
# is separate from the main one, so only this lock differs.
set -euo pipefail
cd "$(dirname "$0")/.."
constraints=requirements/locked-pins-minus-setuptools.txt   # temporary, deleted on exit
trap 'rm -f "$constraints"' EXIT
cat requirements/requirements.lock requirements/requirements-studio.lock | grep -E '^[A-Za-z0-9]' \
    | sed 's/ *\\$//' | grep -v '^setuptools==' | sort -u > "$constraints"
uv pip compile pyproject.toml requirements/requirements-memory.in --all-extras \
    --constraint "$constraints" --python-version 3.13 --exclude-newer 2026-11-01T00:00:00Z \
    --generate-hashes --annotation-style line --no-header -o requirements/requirements-memory.lock.body
{ echo "# Autogenerated by requirements/compile_memory_lock.sh (uv pip compile; see the script)."
  echo "# Install: python -m pip install --require-hashes -r requirements/requirements-memory.lock"
  cat requirements/requirements-memory.lock.body; } > requirements/requirements-memory.lock
rm requirements/requirements-memory.lock.body
